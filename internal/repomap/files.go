package repomap

import (
	"bytes"
	"path"
	"regexp"
	"strings"
)

// langFor names the grammar for a file by its extension ("" when there is none).
func langFor(rel string) string {
	switch strings.ToLower(path.Ext(rel)) {
	case ".go":
		return "go"
	case ".ts", ".mts", ".cts":
		return "typescript"
	case ".tsx":
		return "tsx"
	case ".js", ".mjs", ".cjs", ".jsx":
		return "javascript"
	case ".py", ".pyi":
		return "python"
	case ".cs":
		return "csharp"
	case ".java":
		return "java"
	case ".rs":
		return "rust"
	}
	return ""
}

// vendoredDirs are folders of other people's code (or of tools' output) that a repository sometimes commits. Their files
// would crowd the map with definitions the project only uses.
var vendoredDirs = map[string]bool{
	"node_modules": true, "vendor": true, "third_party": true, "third-party": true, "thirdparty": true, "external": true,
	"bower_components": true, "jspm_packages": true, ".yarn": true, ".pnpm-store": true, "Pods": true, "Carthage": true,
	"site-packages": true, "__pycache__": true, ".venv": true, "venv": true, ".tox": true, ".eggs": true,
	"dist": true, ".next": true, ".nuxt": true, ".svelte-kit": true, ".turbo": true, "coverage": true, ".git": true,
}

func vendored(rel string) bool {
	parts := strings.Split(rel, "/")
	for _, p := range parts[:len(parts)-1] {
		if vendoredDirs[p] {
			return true
		}
	}
	return false
}

// generatedSuffixes name files tools write.
var generatedSuffixes = []string{".min.js", ".min.mjs", ".bundle.js", ".chunk.js", ".pb.go", "_pb2.py", "_pb2_grpc.py", ".pb.cs",
	".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs", "_generated.go", ".gen.go", "_gen.go", ".generated.ts", ".gen.ts"}

func generatedName(rel string) bool {
	l := strings.ToLower(rel)
	for _, s := range generatedSuffixes {
		if strings.HasSuffix(l, s) {
			return true
		}
	}
	return false
}

// generatedRe matches the markers tools put at the top of the files they write (Go's "Code generated ... DO NOT EDIT.",
// "@generated", .NET's "<auto-generated>").
var generatedRe = regexp.MustCompile(`(?i)(code generated .*do not edit|@generated|<auto-generated|this file was automatically generated|autogenerated by)`)

func generatedHeader(src []byte) bool {
	head := src
	if len(head) > 1024 {
		head = head[:1024]
	}
	return generatedRe.Match(head)
}

func isBinary(src []byte) bool {
	head := src
	if len(head) > 8000 {
		head = head[:8000]
	}
	return bytes.IndexByte(head, 0) >= 0
}
