// Package repomap builds the repository map of decisions D5 and P62 with Aider's technique: tree-sitter tags (definitions
// and references) for every source file, a graph of files whose edges are references to identifiers another file defines,
// personalized PageRank over that graph, and a rendering of the most important definition lines (with the lines of the
// definitions that enclose them) that fits a token budget.
//
// The parser is tree-sitter's C library and its grammars, compiled in through CGO (parser_cgo.go). A build without CGO has
// no parser: Available reports false and Map returns ErrNoParser (parser_nocgo.go). Listing, filtering, caching, ranking
// and rendering are pure Go and the same in both builds.
//
// Nothing here writes to the repository or runs anything in it except the git listing the caller provides (Options.List).
// The tags are cached in memory by content hash, and optionally on disk (Options.CacheDir): identifiers and definition
// lines of the person's own code, kept on their own computer, never sent anywhere.
package repomap

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"path"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"sync"
	"time"

	"github.com/kjmaguire/drydock/internal/git"
)

// Token budgets of a map (docs/mcp.md section 8, the repo_map schema).
const (
	DefaultBudget = 2048
	MinBudget     = 256
	MaxBudget     = 8192
)

// Bounds on the work one map does.
const (
	DefaultMaxFiles     = 5000      // source files parsed per map; the rest are counted as over the limit
	DefaultMaxFileBytes = 512 << 10 // a bigger source file is skipped (minified, generated or data)
	maxLineChars        = 100       // a rendered line is cut here, as Aider does
	maxRanked           = 100       // files listed in Result.Ranked
)

// NoParserMessage says why a build without CGO has no repo map.
const NoParserMessage = "this build of Drydock has no repo map: it was built without the C parser (tree-sitter needs CGO; decision D5)"

// ErrNoParser is returned by Map in a build without CGO.
var ErrNoParser = errors.New(NoParserMessage)

// Available reports whether this build has the tree-sitter parser (it was built with CGO).
func Available() bool { return parserBuilt }

// Tag is one definition or reference found in a file.
type Tag struct {
	Name string `json:"n"`
	Def  bool   `json:"d,omitempty"`
	Line int    `json:"l"`           // 0-based line of the name
	End  int    `json:"e,omitempty"` // definitions: 0-based last line of the whole definition (a class's last line)
	Text string `json:"t,omitempty"` // definitions: the line of the name, cut to 100 characters
}

// Lister lists the files of the checkout at root, relative to it with forward slashes, without what .gitignore ignores.
type Lister func(ctx context.Context, root string) ([]string, error)

// GitLister lists with git ls-files (tracked and untracked files, .gitignore respected) through Drydock's hardened git.
func GitLister(ctx context.Context, root string) ([]string, error) {
	r, err := git.Open(ctx, root)
	if err != nil {
		return nil, err
	}
	return r.ListFiles(ctx, root)
}

// Options configures a Mapper. Every field is optional.
type Options struct {
	List         Lister // default GitLister
	MaxFiles     int    // default DefaultMaxFiles
	MaxFileBytes int64  // default DefaultMaxFileBytes
	// CacheDir keeps one file of tags per mapped folder, so the first map after a restart does not parse everything again.
	CacheDir string
	// Workers parse in parallel; default the number of CPUs, at most 8.
	Workers int
}

// Request asks for one map.
type Request struct {
	Root        string   // the checkout to map
	Focus       []string // repo-relative files or folders the map is personalised toward
	TokenBudget int      // MinBudget..MaxBudget; 0 means DefaultBudget
	List        Lister   // overrides Options.List for this request
	CacheDir    string   // overrides Options.CacheDir for this request (a project keeps its cache in its own data folder)
	// CacheKey names the disk cache file within the cache folder; default Root. Checkouts of one repository (a project's
	// task worktrees) share a key, so each new worktree does not leave a cache file of its own behind.
	CacheKey string
}

// RankedFile is one file's place in the ranking.
type RankedFile struct {
	Path  string  `json:"path"`
	Lang  string  `json:"lang"`
	Rank  float64 `json:"rank"`
	Defs  int     `json:"defs"`
	Refs  int     `json:"refs"`
	Focus bool    `json:"focus,omitempty"`
	Shown bool    `json:"shown"` // the file is in the rendered map
}

// Skipped counts the listed files that were not parsed, by reason. Files .gitignore ignores are never listed.
type Skipped struct {
	Unsupported int `json:"unsupported"` // no grammar for the extension (Markdown, JSON, images, ...)
	Vendored    int `json:"vendored"`    // node_modules, vendor, third_party and the like
	Generated   int `json:"generated"`   // generated by a tool (a header says so, or a name such as .min.js or .pb.go)
	TooLarge    int `json:"tooLarge"`
	Binary      int `json:"binary"`
	Unreadable  int `json:"unreadable"`
	Linked      int `json:"linked"`    // a symbolic link, or a path through one that leads out of the checkout: never read
	OverLimit   int `json:"overLimit"` // beyond MaxFiles
}

// Result is one map and what went into it.
type Result struct {
	Map       string         `json:"map"`
	Tokens    int            `json:"tokens"` // chars/4 estimate of Map (docs/mcp.md section 7)
	Budget    int            `json:"budget"`
	Root      string         `json:"root"`
	Focus     []string       `json:"focus"`
	Listed    int            `json:"listed"` // files git listed
	Files     int            `json:"files"`  // source files parsed (or found in the cache)
	Cached    int            `json:"cached"` // of Files, those whose tags came from the cache
	Shown     int            `json:"shown"`  // files in the rendered map
	Defs      int            `json:"defs"`
	Refs      int            `json:"refs"`
	Languages map[string]int `json:"languages"`
	Skipped   Skipped        `json:"skipped"`
	Ranked    []RankedFile   `json:"ranked"`
	ElapsedMs int64          `json:"elapsedMs"`
}

// Mapper makes maps and keeps the tag cache between them. It is safe for concurrent use.
type Mapper struct {
	opts    Options
	extract func(ctx context.Context, lang string, src []byte) ([]Tag, error)
	version string // of the parser and queries: a disk cache made by another version is ignored

	mu     sync.Mutex
	tags   map[string][]Tag    // content hash -> tags
	stats  map[string]statInfo // absolute path -> what the file was when last read
	loaded map[string]bool     // disk cache files already read
	saved  map[string]string   // disk cache file -> fingerprint of the hashes it holds
}

type statInfo struct {
	size int64
	mod  int64
	hash string // content hash; empty when the file was skipped
	skip string // why it was skipped (a Skipped field name)
}

// New returns a Mapper.
func New(opts Options) *Mapper {
	if opts.List == nil {
		opts.List = GitLister
	}
	if opts.MaxFiles <= 0 {
		opts.MaxFiles = DefaultMaxFiles
	}
	if opts.MaxFileBytes <= 0 {
		opts.MaxFileBytes = DefaultMaxFileBytes
	}
	if opts.Workers <= 0 {
		opts.Workers = min(runtime.NumCPU(), 8)
	}
	m := &Mapper{opts: opts, version: parserVersion(), tags: map[string][]Tag{}, stats: map[string]statInfo{}, loaded: map[string]bool{}, saved: map[string]string{}}
	if parserBuilt {
		m.extract = extractTags
	}
	return m
}

// ClampBudget keeps a requested budget inside MinBudget..MaxBudget (0: DefaultBudget).
func ClampBudget(b int) int {
	switch {
	case b == 0:
		return DefaultBudget
	case b < MinBudget:
		return MinBudget
	case b > MaxBudget:
		return MaxBudget
	}
	return b
}

// CleanFocus turns focus entries into clean repo-relative paths with forward slashes. Absolute paths and paths that climb
// out of the checkout are refused.
func CleanFocus(focus []string) ([]string, error) {
	var out []string
	for _, f := range focus {
		f = strings.TrimSpace(strings.ReplaceAll(f, "\\", "/"))
		if f == "" {
			continue
		}
		if strings.HasPrefix(f, "/") || (len(f) > 1 && f[1] == ':') {
			return nil, fmt.Errorf("focus path %q: give a path relative to the repository", f)
		}
		c := path.Clean(f)
		if c == ".." || strings.HasPrefix(c, "../") {
			return nil, fmt.Errorf("focus path %q is outside the repository", f)
		}
		if c != "." {
			out = append(out, c)
		}
	}
	return out, nil
}

// Map builds the map of req.Root.
func (m *Mapper) Map(ctx context.Context, req Request) (Result, error) {
	start := time.Now()
	res := Result{Budget: ClampBudget(req.TokenBudget), Languages: map[string]int{}}
	if m.extract == nil {
		return res, ErrNoParser
	}
	focus, err := CleanFocus(req.Focus)
	if err != nil {
		return res, err
	}
	res.Focus = focus
	root, err := filepath.Abs(req.Root)
	if err != nil {
		return res, err
	}
	res.Root = root
	list := m.opts.List
	if req.List != nil {
		list = req.List
	}
	cacheDir := m.opts.CacheDir
	if req.CacheDir != "" {
		cacheDir = req.CacheDir
	}
	listed, err := list(ctx, root)
	if err != nil {
		return res, fmt.Errorf("listing the repository's files: %w", err)
	}
	res.Listed = len(listed)
	// files are read only where they really are inside the checkout: no link on the way (confiner)
	cf := &confiner{root: root, dirs: map[string]string{}}
	cacheKey := root
	if req.CacheKey != "" {
		cacheKey = req.CacheKey
	}
	m.loadDisk(cacheDir, cacheKey)

	type cand struct{ rel, lang string }
	var cands []cand
	sort.Strings(listed)
	for _, rel := range listed {
		lang := langFor(rel)
		switch {
		case lang == "":
			res.Skipped.Unsupported++
		case vendored(rel):
			res.Skipped.Vendored++
		case generatedName(rel):
			res.Skipped.Generated++
		case len(cands) >= m.opts.MaxFiles:
			res.Skipped.OverLimit++
		default:
			cands = append(cands, cand{rel, lang})
		}
	}

	files := make([]fileTags, len(cands))
	skips := make([]string, len(cands))
	cachedHits := make([]bool, len(cands))
	errs := make([]error, len(cands))
	jobs := make(chan int)
	var wg sync.WaitGroup
	for w := 0; w < m.opts.Workers; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range jobs {
				c := cands[i]
				tags, skip, hit, err := m.fileTags(ctx, cf, c.rel, c.lang)
				files[i] = fileTags{Path: c.rel, Lang: c.lang, Tags: tags}
				skips[i], cachedHits[i], errs[i] = skip, hit, err
			}
		}()
	}
	for i := range cands {
		if ctx.Err() != nil {
			break
		}
		jobs <- i
	}
	close(jobs)
	wg.Wait()
	if err := ctx.Err(); err != nil {
		return res, err
	}
	var parsed []fileTags
	live := map[string]bool{}
	paths := make(map[string]bool, len(cands))
	for _, c := range cands {
		paths[filepath.Join(root, filepath.FromSlash(c.rel))] = true
	}
	for i, f := range files {
		switch skips[i] {
		case "":
		case "tooLarge":
			res.Skipped.TooLarge++
			continue
		case "binary":
			res.Skipped.Binary++
			continue
		case "generated":
			res.Skipped.Generated++
			continue
		case "linked":
			res.Skipped.Linked++
			continue
		default:
			res.Skipped.Unreadable++
			continue
		}
		if errs[i] != nil {
			res.Skipped.Unreadable++
			continue
		}
		parsed = append(parsed, f)
		res.Languages[f.Lang]++
		if cachedHits[i] {
			res.Cached++
		}
		for _, t := range f.Tags {
			if t.Def {
				res.Defs++
			} else {
				res.Refs++
			}
		}
		live[m.hashOf(filepath.Join(root, filepath.FromSlash(f.Path)))] = true
	}
	res.Files = len(parsed)
	m.saveDisk(cacheDir, cacheKey, live, paths)

	focusSet := map[string]bool{}
	for _, f := range parsed {
		if isFocused(f.Path, focus) {
			focusSet[f.Path] = true
		}
	}
	g := rank(parsed, focusSet)
	text, shown := render(g, res.Budget)
	res.Map, res.Tokens, res.Shown = text, EstimateTokens(text), len(shown)
	for i, f := range g.order {
		if i >= maxRanked {
			break
		}
		res.Ranked = append(res.Ranked, RankedFile{Path: f, Lang: g.files[f].Lang, Rank: g.fileRank[f], Defs: g.defCount[f], Refs: g.refCount[f], Focus: focusSet[f], Shown: shown[f]})
	}
	res.ElapsedMs = time.Since(start).Milliseconds()
	return res, nil
}

// EstimateTokens is the chars/4 estimate used everywhere in Drydock (an assumption, not a tokenizer).
func EstimateTokens(s string) int {
	n := len([]rune(s))
	return (n + 3) / 4
}

func isFocused(rel string, focus []string) bool {
	for _, f := range focus {
		if rel == f || strings.HasPrefix(rel, f+"/") {
			return true
		}
	}
	return false
}

// fileTags returns the tags of one file, from the cache when its size, time and (on a change) content say it is the same.
// The file is read only when it is a regular file inside the checkout (confiner): a link is skipped as "linked".
func (m *Mapper) fileTags(ctx context.Context, cf *confiner, rel, lang string) (tags []Tag, skip string, cached bool, err error) {
	abs := filepath.Join(cf.root, filepath.FromSlash(rel))
	if why := cf.dirCheck(path.Dir(rel)); why != "" {
		return nil, why, false, nil
	}
	st, err := os.Lstat(abs)
	switch {
	case err != nil:
		return nil, "unreadable", false, nil
	case st.Mode()&os.ModeSymlink != 0:
		return nil, "linked", false, nil
	case !st.Mode().IsRegular():
		return nil, "unreadable", false, nil
	case st.Size() > m.opts.MaxFileBytes:
		return nil, "tooLarge", false, nil
	}
	m.mu.Lock()
	prev, ok := m.stats[abs]
	if ok && prev.size == st.Size() && prev.mod == st.ModTime().UnixNano() && prev.skip != "linked" {
		if prev.skip != "" {
			m.mu.Unlock()
			return nil, prev.skip, true, nil
		}
		if t, ok := m.tags[prev.hash]; ok {
			m.mu.Unlock()
			return t, "", true, nil
		}
	}
	m.mu.Unlock()
	src, skip := readSame(abs, st, m.opts.MaxFileBytes)
	if skip != "" {
		return nil, skip, false, nil
	}
	info := statInfo{size: st.Size(), mod: st.ModTime().UnixNano()}
	switch {
	case isBinary(src):
		info.skip = "binary"
	case generatedHeader(src):
		info.skip = "generated"
	}
	if info.skip != "" {
		m.mu.Lock()
		m.stats[abs] = info
		m.mu.Unlock()
		return nil, info.skip, false, nil
	}
	sum := sha256.Sum256(append([]byte(lang+"\x00"), src...))
	info.hash = hex.EncodeToString(sum[:])
	m.mu.Lock()
	t, hit := m.tags[info.hash]
	m.stats[abs] = info
	m.mu.Unlock()
	if hit {
		return t, "", true, nil
	}
	t, err = m.extract(ctx, lang, src)
	if err != nil {
		return nil, "", false, err
	}
	m.mu.Lock()
	m.tags[info.hash] = t
	m.mu.Unlock()
	return t, "", false, nil
}

// confiner keeps a map's reads inside its checkout. git lists a tracked file by its path even when a folder on that path
// was replaced by a link (or, on Windows, a junction) to somewhere else, so every folder between the root and a file must
// be a real folder; the root itself may be reached through a link. Folder answers are kept for the map.
type confiner struct {
	root string
	mu   sync.Mutex
	dirs map[string]string // repo-relative folder -> "" (it and every folder above it are real folders), "linked" or "unreadable"
}

// dirCheck says whether files in dir may be read: "" yes, "linked" when a folder on the way is a link or junction,
// "unreadable" when one is missing (deleted since git listed it) or cannot be read.
func (c *confiner) dirCheck(dir string) string {
	if dir == "." || dir == "" {
		return ""
	}
	c.mu.Lock()
	why, seen := c.dirs[dir]
	c.mu.Unlock()
	if seen {
		return why
	}
	why = c.dirCheck(path.Dir(dir))
	if why == "" {
		st, err := os.Lstat(filepath.Join(c.root, filepath.FromSlash(dir)))
		switch {
		case err != nil:
			why = "unreadable"
		case st.Mode()&(os.ModeSymlink|os.ModeIrregular) != 0:
			why = "linked"
		case !st.IsDir():
			why = "unreadable"
		}
	}
	c.mu.Lock()
	c.dirs[dir] = why
	c.mu.Unlock()
	return why
}

// readSame reads abs only when what it opens is the regular file lst described: a file swapped for a link after lst was
// taken is "linked".
func readSame(abs string, lst os.FileInfo, maxBytes int64) ([]byte, string) {
	f, err := os.Open(abs)
	if err != nil {
		return nil, "unreadable"
	}
	defer f.Close()
	fst, err := f.Stat()
	if err != nil {
		return nil, "unreadable"
	}
	if !os.SameFile(lst, fst) {
		return nil, "linked"
	}
	src, err := io.ReadAll(io.LimitReader(f, maxBytes+1))
	switch {
	case err != nil:
		return nil, "unreadable"
	case int64(len(src)) > maxBytes:
		return nil, "tooLarge"
	}
	return src, ""
}

func (m *Mapper) hashOf(abs string) string {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.stats[abs].hash
}
