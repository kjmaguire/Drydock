package agui

import (
	"reflect"

	"github.com/kjmaguire/drydock/internal/tsgen"
)

// TSPath is where the generated TypeScript lives, from the repository root.
const TSPath = "ui/app/api/agui.gen.ts"

// TypeScript returns the UI's types for the vocabulary: one interface per event with its type fixed, the AguiEvent union,
// and the thread and activity a task's activity is read as. cmd/drydock-tsgen writes it to TSPath.
func TypeScript() (string, error) {
	events := []struct {
		name string
		typ  string
		v    any
	}{
		{"RunStartedEvent", TypeRunStarted, RunStarted{}},
		{"RunFinishedEvent", TypeRunFinished, RunFinished{}},
		{"RunErrorEvent", TypeRunError, RunError{}},
		{"TextMessageStartEvent", TypeTextMessageStart, TextMessageStart{}},
		{"TextMessageContentEvent", TypeTextMessageContent, TextMessageContent{}},
		{"TextMessageEndEvent", TypeTextMessageEnd, TextMessageEnd{}},
		{"ReasoningMessageStartEvent", TypeReasoningMessageStart, ReasoningMessageStart{}},
		{"ReasoningMessageContentEvent", TypeReasoningMessageContent, ReasoningMessageContent{}},
		{"ReasoningMessageEndEvent", TypeReasoningMessageEnd, ReasoningMessageEnd{}},
		{"ToolCallStartEvent", TypeToolCallStart, ToolCallStart{}},
		{"ToolCallArgsEvent", TypeToolCallArgs, ToolCallArgs{}},
		{"ToolCallEndEvent", TypeToolCallEnd, ToolCallEnd{}},
		{"ToolCallResultEvent", TypeToolCallResult, ToolCallResult{}},
		{"ActivitySnapshotEvent", TypeActivitySnapshot, ActivitySnapshot{}},
	}
	customs := []struct {
		name, event string
		v           any
	}{
		{"InterruptEvent", NameInterrupt, Interrupt{}},
		{"ResumeEvent", NameResume, Resume{}},
		{"DecidedEvent", NameDecided, Decided{}},
	}
	f := tsgen.File{
		Header: `// Generated by cmd/drydock-tsgen from internal/agui (decision P87). Do not edit: change the Go types and run
// "go run ./cmd/drydock-tsgen". A Go test fails while this file differs from what the types generate.
//
// What an agent does during a run, in a vocabulary modelled on the AG-UI protocol 1.0. What Drydock adds beyond AG-UI's own
// fields is under metadata.drydock (DrydockMeta).
`,
		Consts: tsgen.SortedConsts(map[string]string{
			"ACTIVITY_PLAN": ActivityPlan, "OUTCOME_SUCCESS": OutcomeSuccess, "OUTCOME_CANCELLED": OutcomeCancelled,
			"CUSTOM_INTERRUPT": NameInterrupt, "CUSTOM_RESUME": NameResume, "CUSTOM_DECIDED": NameDecided, "DECIDED_REFUSED": DecidedRefused,
			"CUT_MARKER": CutMarker, "CUT_MIDDLE_MARKER": CutMiddleMarker, "PROTOCOL_VERSION": ProtocolVersion,
		}),
	}
	u := tsgen.Union{Name: "AguiEvent", Doc: "Any event of the vocabulary; narrow it on `type`."}
	for _, e := range events {
		lit := map[string]string{"type": e.typ}
		if e.typ == TypeReasoningMessageStart {
			lit["role"] = "reasoning" // AG-UI fixes it
		}
		if e.typ == TypeRunStarted {
			lit["protocolVersion"] = ProtocolVersion
		}
		f.Decls = append(f.Decls, tsgen.Decl{Name: e.name, Type: reflect.TypeOf(e.v), Literal: lit})
		u.Members = append(u.Members, e.name)
	}
	for _, c := range customs {
		f.Decls = append(f.Decls, tsgen.Decl{Name: c.name, Type: reflect.TypeOf(c.v), Literal: map[string]string{"type": TypeCustom, "name": c.event}})
		u.Members = append(u.Members, c.name)
	}
	f.Unions = []tsgen.Union{u}
	f.Refs = map[reflect.Type]string{reflect.TypeOf(aguiTSEv{}): "AguiEvent"}
	f.Decls = append(f.Decls,
		tsgen.Decl{Name: "AguiThread", Doc: "One agent process's events: a valid stream on its own. It ended when its process is gone (a thread with no events that ended was stopped before its first turn).", Type: reflect.TypeOf(threadTS{})},
		tsgen.Decl{Name: "AguiActivity", Doc: "A task's threads in the order they started; truncated when the oldest events were left out.", Type: reflect.TypeOf(activityTS{})},
	)
	return tsgen.Generate(f)
}

// threadTS and activityTS are Thread and Activity as the UI reads them: their events are the union.
type threadTS struct {
	ThreadID  string     `json:"threadId"`
	AgentID   string     `json:"agentId,omitempty"`
	Adapter   string     `json:"adapter,omitempty"`
	Model     string     `json:"model,omitempty"`
	RunMode   string     `json:"runMode,omitempty"`
	WSLDistro string     `json:"wslDistro,omitempty"`
	Ended     bool       `json:"ended,omitempty"`
	Events    []aguiTSEv `json:"events"`
}

// aguiTSEv stands for the AguiEvent union in the generated types.
type aguiTSEv struct{}

type activityTS struct {
	Threads   []threadTS `json:"threads"`
	Truncated bool       `json:"truncated,omitempty"`
}
