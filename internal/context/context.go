// Package context is the Context Engine (brief section 9): it decides what each agent run receives, records a manifest
// of what was included and excluded and why, and owns the generated instruction files (AGENTS.md canonical, one-line
// import files for the other CLIs) written into every worktree.
package context

import (
	"context"
	"crypto/sha256"
	"database/sql"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/kjmaguire/drydock/internal/memory"
	"github.com/kjmaguire/drydock/internal/storage"
)

// Item is one line of a context manifest.
type Item struct {
	Source   string `json:"source"`
	Included bool   `json:"included"`
	Bytes    int    `json:"bytes"`
	Reason   string `json:"reason"`
	Priority int    `json:"priority"`
}

// Manifest records what a run was given (and what was left out on purpose).
type Manifest struct {
	Items []Item `json:"items"`
}

// Add appends an item.
func (m *Manifest) Add(source string, included bool, bytes int, reason string, priority int) {
	m.Items = append(m.Items, Item{Source: source, Included: included, Bytes: bytes, Reason: reason, Priority: priority})
}

// IncludedBytes sums included sizes.
func (m Manifest) IncludedBytes() int {
	n := 0
	for _, i := range m.Items {
		if i.Included {
			n += i.Bytes
		}
	}
	return n
}

// Engine builds context.
type Engine struct {
	DB     *storage.DB
	Memory memory.Store
	// Standing returns the project's standing instructions text (settings).
	Standing func(ctx context.Context, projectID string) string
	// Sections and Files (optional, see hooks.go) let attached packs and skills add AGENTS.md sections and app-owned files
	// such as .claude/rules/<name>.md to a worktree.
	Sections SectionsFunc
	Files    FilesFunc
}

const headerPrefix = "<!-- drydock:generated sha256="

// generated file names and their roles.
var (
	canonical = "AGENTS.md"
	importers = map[string]string{
		"CLAUDE.md": "@AGENTS.md\n",
		"GEMINI.md": "@AGENTS.md\n",
	}
	// .goosehints is not generated: Goose reads AGENTS.md natively and whether it also concatenates .goosehints is unverified
	// (docs/connections.md section 14), so writing the same content there could double-load it.
)

// Files is the generated instruction files by repo-relative path.
type Files map[string]string

// Names lists the generated file paths in stable order.
func (f Files) Names() []string {
	var n []string
	for k := range f {
		n = append(n, k)
	}
	sort.Strings(n)
	return n
}

// Generate renders the instruction files for a project. existing is the repository's own content for each file name
// (read from the worktree before Drydock overwrites it): user-authored files are imported as a section, never lost.
func (e *Engine) Generate(ctx context.Context, projectID string, existing map[string]string) (Files, Manifest, error) {
	return e.generate(ctx, projectID, "", existing)
}

func (e *Engine) generate(ctx context.Context, projectID, worktree string, existing map[string]string) (Files, Manifest, error) {
	var m Manifest
	var sb strings.Builder
	sb.WriteString("# Project instructions\n\n")
	sb.WriteString("These instructions are generated by Drydock from the project's accepted memory. They apply to every task in this repository.\n")

	standing := ""
	if e.Standing != nil {
		standing = strings.TrimSpace(e.Standing(ctx, projectID))
	}
	if standing != "" {
		sb.WriteString("\n## Standing instructions\n\n" + standing + "\n")
		m.Add("standing instructions", true, len(standing), "project setting", 10)
	}
	// user-authored instruction files already in the repo are kept, as an imported section
	for _, name := range []string{"AGENTS.md", "CLAUDE.md", "GEMINI.md", ".goosehints"} {
		body, ok := existing[name]
		if !ok || strings.HasPrefix(strings.TrimSpace(body), headerPrefix) || strings.TrimSpace(body) == "" {
			continue
		}
		if t := strings.TrimSpace(body); t == "@AGENTS.md" {
			continue
		}
		sb.WriteString("\n## From the repository's own " + name + "\n\n" + strings.TrimSpace(body) + "\n")
		m.Add("repo:"+name, true, len(body), "existing instruction file imported (not overwritten in git)", 20)
	}
	entries, err := e.Memory.List(ctx, projectID, memory.Accepted, "")
	if err != nil {
		return nil, m, err
	}
	sections := []struct{ kind, title string }{
		{memory.Decision, "Architecture decisions"}, {memory.Convention, "Conventions"}, {memory.APIContract, "API contracts"},
		{memory.Rejected, "Rejected approaches (do not retry)"}, {memory.KnownIssue, "Known issues"}, {memory.Preference, "Preferences"},
	}
	for _, sec := range sections {
		var lines []string
		for _, en := range entries {
			if en.Kind == sec.kind {
				lines = append(lines, fmt.Sprintf("- **%s**: %s", en.Title, oneLine(en.Body)))
				m.Add("memory:"+en.ID, true, len(en.Title)+len(en.Body), sec.title, 30)
			}
		}
		if len(lines) > 0 {
			sb.WriteString("\n## " + sec.title + "\n\n" + strings.Join(lines, "\n") + "\n")
		}
	}
	if e.Sections != nil {
		extra, err := e.Sections(ctx, projectID, worktree)
		if err != nil {
			return nil, m, err
		}
		sort.SliceStable(extra, func(i, j int) bool {
			if extra[i].Priority != extra[j].Priority {
				return extra[i].Priority < extra[j].Priority
			}
			return extra[i].Title < extra[j].Title
		})
		for _, sec := range extra {
			if strings.TrimSpace(sec.Body) == "" {
				continue
			}
			sb.WriteString("\n## " + sec.Title + "\n\n" + strings.TrimSpace(sec.Body) + "\n")
			m.Add(sec.Source, true, len(sec.Body), sec.Reason, sec.Priority)
		}
	}
	sb.WriteString(`
## How to work here

- Deterministic tools answer before any model: tests, linters, type checks and secret scans run for you; their results arrive as evidence. Do not re-run them to "check" them.
- Look things up instead of guessing: use the workspace tools (search memory, search requirements, read a file range) rather than asking for documentation to be pasted.
- Keep changes minimal and stay inside the task. Do not commit; Drydock commits after the checks pass.
- If you are stuck, say what is blocking you and propose a different approach before using more tools.
`)
	body := sb.String()
	out := Files{}
	out[canonical] = stamp(body)
	for name, content := range importers {
		out[name] = stamp(content)
	}
	for _, n := range out.Names() {
		m.Add("file:"+n, true, len(out[n]), "generated instruction file", 5)
	}
	return out, m, nil
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func hash(s string) string {
	h := sha256.Sum256([]byte(s))
	return hex.EncodeToString(h[:])
}

// stamp prepends the ownership header: the hash of the body lets a later regeneration detect human edits.
func stamp(body string) string {
	return headerPrefix + hash(body)[:16] + " -->\n" + body
}

// bodyOf splits a stamped file into (recorded hash prefix, body).
func bodyOf(content string) (string, string, bool) {
	if !strings.HasPrefix(content, headerPrefix) {
		return "", content, false
	}
	nl := strings.IndexByte(content, '\n')
	if nl < 0 {
		return "", "", false
	}
	h := strings.TrimSuffix(strings.TrimPrefix(content[:nl], headerPrefix), " -->")
	return h, content[nl+1:], true
}

// WriteResult describes what Write did.
type WriteResult struct {
	Written  []string
	Imported []string // user-authored files whose content was folded into AGENTS.md
	Edited   []string // generated files a human edited: left alone, edit offered back as a memory proposal
	// Extras are the files written for other subsystems (also listed in Written); SkippedExtras were left alone because they
	// are the repository's own files or their path was refused.
	Extras        []string
	SkippedExtras []string
}

// Write materialises the instruction files into a worktree. User-authored files are read first and imported into the
// generated AGENTS.md. A previously generated file whose body no longer matches its header was edited by a human: it is
// not overwritten; its text is offered back as a proposed memory entry. Callers keep the files out of commits
// (git.LocalIgnore).
func (e *Engine) Write(ctx context.Context, projectID, worktree string) (WriteResult, Manifest, error) {
	var res WriteResult
	existing := map[string]string{}
	for _, name := range []string{"AGENTS.md", "CLAUDE.md", "GEMINI.md", ".goosehints"} {
		if b, err := os.ReadFile(filepath.Join(worktree, name)); err == nil {
			existing[name] = string(b)
		}
	}
	files, m, err := e.generate(ctx, projectID, worktree, existing)
	if err != nil {
		return res, m, err
	}
	for _, name := range files.Names() {
		path := filepath.Join(worktree, name)
		if cur, ok := existing[name]; ok {
			if h, body, stamped := bodyOf(cur); stamped {
				if hash(body)[:16] != h {
					res.Edited = append(res.Edited, name)
					_, _ = e.Memory.Add(ctx, memory.Entry{ProjectID: projectID, Kind: memory.Preference, Title: "Human edit to " + name, Body: strings.TrimSpace(body), Source: "edit:" + name}, false)
					continue
				}
			} else {
				res.Imported = append(res.Imported, name)
			}
		}
		if err := os.WriteFile(path, []byte(files[name]), 0o644); err != nil {
			return res, m, err
		}
		res.Written = append(res.Written, name)
		_ = e.recordGenerated(ctx, projectID, name, files[name])
	}
	extras, skipped, err := e.writeExtras(ctx, projectID, worktree, &m)
	if err != nil {
		return res, m, err
	}
	res.Written = append(res.Written, extras...) // extras are app-owned too: the caller keeps them out of git
	res.Extras, res.SkippedExtras = extras, skipped
	return res, m, nil
}

func (e *Engine) recordGenerated(ctx context.Context, projectID, path, content string) error {
	_, body, _ := bodyOf(content)
	return e.DB.WriteTx(ctx, func(tx *sql.Tx) error {
		_, err := tx.ExecContext(ctx, `INSERT INTO generated_files(project_id,path,body_sha,generated_at) VALUES(?,?,?,?)
			ON CONFLICT(project_id,path) DO UPDATE SET body_sha=excluded.body_sha, generated_at=excluded.generated_at`, projectID, path, hash(body)[:16], storage.Now())
		return err
	})
}

// SaveManifest stores a run's manifest for the Agent Inspector.
func (e *Engine) SaveManifest(ctx context.Context, runID, nodeID string, attempt int, taskID, agentID string, m Manifest) error {
	b, _ := json.Marshal(m.Items)
	return e.DB.WriteTx(ctx, func(tx *sql.Tx) error {
		_, err := tx.ExecContext(ctx, `INSERT INTO context_manifests(run_id,node_id,attempt,task_id,agent_id,items,total_bytes,created_at) VALUES(?,?,?,?,?,?,?,?)
			ON CONFLICT(run_id,node_id,attempt) DO UPDATE SET items=excluded.items,total_bytes=excluded.total_bytes`,
			runID, nodeID, attempt, taskID, agentID, string(b), m.IncludedBytes(), storage.Now())
		return err
	})
}

// LoadManifest reads a stored manifest.
func (e *Engine) LoadManifest(ctx context.Context, runID, nodeID string, attempt int) (Manifest, error) {
	var items string
	err := e.DB.Reader().QueryRowContext(ctx, `SELECT items FROM context_manifests WHERE run_id=? AND node_id=? AND attempt=?`, runID, nodeID, attempt).Scan(&items)
	var m Manifest
	if err != nil {
		return m, err
	}
	return m, json.Unmarshal([]byte(items), &m.Items)
}
