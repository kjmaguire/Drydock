// recordFS records every path the importer lists, inspects or opens, for the test's lifetime.
func recordFS(t *testing.T) func() []string {
	t.Helper()
	var mu sync.Mutex
	var seen []string
	keep := transcriptFS
	note := func(p string) {
		mu.Lock()
		seen = append(seen, p)
		mu.Unlock()
	}
	transcriptFS.readDir = func(p string) ([]os.DirEntry, error) { note(p); return keep.readDir(p) }
	transcriptFS.lstat = func(p string) (os.FileInfo, error) { note(p); return keep.lstat(p) }
	transcriptFS.open = func(p string) (*os.File, error) { note("open " + p); return keep.open(p) }
	t.Cleanup(func() { transcriptFS = keep })
	return func() []string {
		mu.Lock()
		defer mu.Unlock()
		return append([]string(nil), seen...)
	}
}

func newImportService(t *testing.T, f importFixture) (*Service, *storage.DB) {
	t.Helper()
	ctx := context.Background()
	db, err := storage.OpenTemp(ctx, t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() })
	sc, err := security.NewScanner()
	if err != nil {
		t.Fatal(err)
	}
	s := New(Deps{DB: db, Runtime: &rt.Runtime{}, Redact: sc.Redact,
		Capabilities: func(id string) (agents.Capabilities, bool) {
			return agents.Capabilities{Headless: true, SessionResume: true, PermissionModes: []string{"default", "acceptEdits", "plan"}}, id == "claude"
		},
		ClaudeSources: func(context.Context) []ClaudeSource {
			return []ClaudeSource{{Projects: f.projects, Folder: func(cwd string) (string, bool) { return filepath.Clean(cwd), filepath.IsAbs(cwd) }}}
		},
		ProjectFor: func(_ context.Context, distro, dir string) string {
			if distro == "" && dir == filepath.Clean(f.repo) {
				return "prj_repo"
			}
			return ""
		},
	}, Options{})
	t.Cleanup(s.Close)
	return s, db
}

func TestImportClaudeCodeChats(t *testing.T) {
	ctx := context.Background()
	f := newImportFixture(t)
	touched := recordFS(t)
	s, db := newImportService(t, f)

	list, err := s.ImportClaudeCodeList(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if len(list.Sessions) != 2 || list.Sessions[0].SessionID != sessB || list.Sessions[1].SessionID != sessA {
		t.Fatalf("the sessions, the most recent first: %+v", list.Sessions)
	}
	a, b := list.Sessions[1], list.Sessions[0]
	if a.Title != "Fix the parser tests" || a.Cwd != filepath.Clean(f.repo) || a.ProjectID != "prj_repo" || a.Messages != 3 || a.ChatID != "" || a.Problem != "" {
		t.Fatalf("session A: %+v", a)
	}
	if b.Title != "What does" || b.ProjectID != "" || b.Messages != 2 {
		t.Fatalf("session B (titled by its first line): %+v", b)
	}
	if len(list.Sources) != 1 || list.Sources[0].Sessions != 2 || list.Sources[0].Skipped != 1 || list.Sources[0].Error != "" {
		t.Fatalf("the source (the link to the sign-in is skipped): %+v", list.Sources)
	}

	res, err := s.ImportClaudeCode(ctx, ImportReq{Sessions: []ImportRef{{SessionID: sessA}, {SessionID: sessB}}})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Imported) != 2 || len(res.Skipped) != 0 {
		t.Fatalf("the import: %+v", res)
	}
	c := res.Imported[0].Chat
	if c.SessionID != sessA || c.ImportedSession != sessA || c.ImportedFrom != ImportSourceClaudeCode || c.Adapter != "claude" || c.WSLDistro != "" ||
		c.Cwd != filepath.Clean(f.repo) || c.ProjectID != "prj_repo" || c.Title != "Fix the parser tests" || c.PermissionMode != "default" || c.Status != StatusIdle {
		t.Fatalf("the imported chat: %+v", c)
	}
	if c.Created != time.Date(2026, 9, 1, 10, 0, 0, 0, time.UTC).UnixMilli() || c.Updated != time.Date(2026, 9, 1, 10, 8, 0, 0, time.UTC).UnixMilli() {
		t.Fatalf("the chat's times are not the session's: created %d updated %d", c.Created, c.Updated)
	}
	d, err := s.Detail(ctx, c.ID, 200)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, m := range d.Messages {
		got = append(got, m.Role+":"+m.Body)
	}
	if len(got) != 5 || !strings.HasPrefix(got[0], "user:The parser tests fail.") || got[1] != "assistant:Let me run them." ||
		got[2] != "tool:Used tool Bash" || got[3] != "assistant:The test expected a trailing newline.\n\nI fixed it." ||
		!strings.HasPrefix(got[4], "system:Imported from Claude Code (session "+sessA+")") {
		t.Fatalf("the messages:\n%s", strings.Join(got, "\n"))
	}
	if d.Messages[0].Created != time.Date(2026, 9, 1, 10, 2, 0, 0, time.UTC).UnixMilli() {
		t.Fatalf("the first message is stamped %d, not when it was typed", d.Messages[0].Created)
	}
	if d.Messages[2].ToolName != "Bash" || d.Messages[2].ToolStatus != ToolFailed {
		t.Fatalf("the tool call: %+v", d.Messages[2])
	}
	// the secret is nowhere in the database, the thinking and the sub-agent are not imported
	for _, q := range []string{`SELECT COUNT(*) FROM chat_messages WHERE body LIKE '%ghp_%' OR body LIKE '%hidden reasoning%' OR body LIKE '%sub-agent%' OR body LIKE '%command-name%'`,
		`SELECT COUNT(*) FROM chats WHERE title LIKE '%ghp_%'`} {
		var n int
		if err := db.Reader().QueryRowContext(ctx, q).Scan(&n); err != nil || n != 0 {
			t.Fatalf("%s: %d (%v)", q, n, err)
		}
	}
	if !strings.Contains(got[0], "do not print it") {
		t.Fatalf("the redacted message lost its text: %s", got[0])
	}

	// a second import does nothing, and the list says where each one went
	again, err := s.ImportClaudeCode(ctx, ImportReq{Sessions: []ImportRef{{SessionID: sessA}, {SessionID: sessB}}})
	if err != nil {
		t.Fatal(err)
	}
	if len(again.Imported) != 0 || len(again.Skipped) != 2 || again.Skipped[0].ChatID != c.ID || again.Skipped[0].Reason != "Imported already." {
		t.Fatalf("the second import: %+v", again)
	}
	var chats int
	_ = db.Reader().QueryRowContext(ctx, `SELECT COUNT(*) FROM chats`).Scan(&chats)
	if chats != 2 {
		t.Fatalf("%d chats after importing twice", chats)
	}
	list, _ = s.ImportClaudeCodeList(ctx)
	if list.Sessions[1].ChatID != c.ID || list.Sessions[0].ChatID != res.Imported[1].Chat.ID {
		t.Fatalf("the list after the import: %+v", list.Sessions)
	}
	// a session Drydock's own chat runs (here: B's chat continued in a new session, as the CLI may report) is not listed
	if _, err := db.Writer().ExecContext(ctx, `INSERT INTO chat_turns(id,chat_id,status,session_id,started_at) VALUES('cturn_x',?,'done',?,1)`, res.Imported[1].Chat.ID, "5c5c5c5c-0000-4000-8000-000000000004"); err != nil {
		t.Fatal(err)
	}
	writeLines(t, filepath.Join(f.projects, "-other", "5c5c5c5c-0000-4000-8000-000000000004.jsonl"),
		tline(map[string]any{"type": "user", "cwd": f.other, "timestamp": tstamp(30), "message": map[string]any{"role": "user", "content": "go on"}}))
	if list, _ = s.ImportClaudeCodeList(ctx); len(list.Sessions) != 2 {
		t.Fatalf("Drydock's own session is listed: %+v", list.Sessions)
	}

	// deleting the imported chat frees its session to be imported again
	if err := s.Delete(ctx, c.ID); err != nil {
		t.Fatal(err)
	}
	if res, err = s.ImportClaudeCode(ctx, ImportReq{Sessions: []ImportRef{{SessionID: sessA}}}); err != nil || len(res.Imported) != 1 {
		t.Fatalf("importing a deleted chat's session again: %+v %v", res, err)
	}

	// only the projects folder was listed, and only session files in it were opened: never the sign-in, the settings, the
	// global config or the plugins, not even through the links inside the projects folder
	for _, p := range touched() {
		opened, isOpen := strings.CutPrefix(p, "open ")
		if !strings.HasPrefix(opened, f.projects) {
			t.Errorf("the import touched %s, outside Claude Code's projects folder", p)
		}
		if isOpen && (!strings.HasSuffix(opened, ".jsonl") || strings.Contains(opened, "9a9a9a9a") || strings.Contains(opened, "-linked")) {
			t.Errorf("the import opened %s", opened)
		}
		if strings.Contains(p, "-linked") && p != filepath.Join(f.projects, "-linked") {
			t.Errorf("the import followed the linked folder: %s", p)
		}
	}
}

// Unknown sessions, a request without sessions and a session without a folder are refused or skipped with the reason.
func TestImportClaudeCodeRefusals(t *testing.T) {
	ctx := context.Background()
	f := newImportFixture(t)
	writeLines(t, filepath.Join(f.projects, "-nowhere", "3e3e3e3e-0000-4000-8000-000000000005.jsonl"),
		tline(map[string]any{"type": "user", "timestamp": tstamp(40), "message": map[string]any{"role": "user", "content": "no folder here"}}))
	s, _ := newImportService(t, f)
	if _, err := s.ImportClaudeCode(ctx, ImportReq{}); err == nil {
		t.Fatal("an import of nothing was accepted")
	}
	list, _ := s.ImportClaudeCodeList(ctx)
	var nowhere ImportCandidate
	for _, c := range list.Sessions {
		if strings.HasPrefix(c.SessionID, "3e3e3e3e") {
			nowhere = c
		}
	}
	if nowhere.Problem == "" || nowhere.Cwd != "" {
		t.Fatalf("a session without a folder: %+v", nowhere)
	}
	res, err := s.ImportClaudeCode(ctx, ImportReq{Sessions: []ImportRef{{SessionID: "3e3e3e3e-0000-4000-8000-000000000005"}, {SessionID: "--help"}, {SessionID: sessA, WSLDistro: "Ubuntu"}}})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Imported) != 0 || len(res.Skipped) != 3 || !strings.Contains(res.Skipped[0].Reason, "folder") || !strings.Contains(res.Skipped[1].Reason, "not found") ||
		!strings.Contains(res.Skipped[2].Reason, "not found") {
		t.Fatalf("the refusals: %+v", res)
	}
}

// The parser's caps: a line over the cap is skipped and counted, the rest of the file still read; a session longer than the
// import keeps keeps its newest messages and says how many were left out.
func TestTranscriptCaps(t *testing.T) {
	keepLine, keepMsgs := maxTranscriptLine, maxImportMessages
	t.Cleanup(func() { maxTranscriptLine, maxImportMessages = keepLine, keepMsgs })
	maxTranscriptLine, maxImportMessages = 200, 2
	in := strings.Join([]string{
		tline(map[string]any{"type": "user", "message": map[string]any{"content": "one"}}),
		tline(map[string]any{"type": "user", "message": map[string]any{"content": strings.Repeat("x", 300)}}),
		tline(map[string]any{"type": "user", "message": map[string]any{"content": "two"}}),
		tline(map[string]any{"type": "user", "message": map[string]any{"content": "three"}}),
	}, "\n")
	tr, err := parseTranscript(strings.NewReader(in), sessA)
	if err != nil {
		t.Fatal(err)
	}
	if tr.skipped != 1 || tr.dropped != 1 || len(tr.msgs) != 2 || tr.msgs[0].body != "two" || tr.msgs[1].body != "three" {
		t.Fatalf("%+v", tr)
	}
}
