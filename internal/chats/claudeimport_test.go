// importSecret is a GitHub token shaped string the scanner knows.
var importSecret = "ghp_" + strings.Repeat("aB3dE5fG7h", 3) + "aB3dE5"

func tline(v map[string]any) string {
	b, _ := json.Marshal(v)
	return string(b)
}

func tstamp(min int) string {
	return time.Date(2026, 9, 1, 10, min, 0, 0, time.UTC).Format("2006-01-02T15:04:05.000Z")
}

func writeLines(t *testing.T, path string, lines ...string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
}

